#!/usr/bin/env bash
# The local Langfuse stack (observability/docker-compose.langfuse.yml): up, down, or the round-trip check.
#
#   up     generate local credentials into the git-ignored env file (only if it does not exist yet), start the stack,
#          wait until Langfuse answers on /api/public/health
#   down   stop the stack, remove its containers AND volumes, delete the env file
#   check  replay one committed turn with the Langfuse exporter (no model call) and read it back through the API
#
# pierre has no users: what this dashboard shows is a small scheduled canary of held-out cases. Nothing here prints a
# credential; the env file is mode 600 and git-ignored.
set -euo pipefail

cd "$(dirname "$0")/../.."  # the repository root
COMPOSE_FILE=observability/docker-compose.langfuse.yml
ENV_FILE=observability/.env.langfuse
PROJECT=pierre-langfuse
PY=${PY:-.venv/bin/python}

compose() { docker compose -p "$PROJECT" -f "$COMPOSE_FILE" --env-file "$1" "${@:2}"; }

generate_env() {
  if git rev-parse --is-inside-work-tree >/dev/null 2>&1 && ! git check-ignore -q "$ENV_FILE"; then
    echo "refusing to write $ENV_FILE: it is not git-ignored" >&2
    exit 1
  fi
  umask 077
  python3 - "$ENV_FILE" <<'EOF'
import secrets, sys
h = secrets.token_hex
port = "3000"
values = {
    "LANGFUSE_PORT": port,
    "LANGFUSE_HOST": f"http://localhost:{port}",
    "POSTGRES_PASSWORD": (pg := h(24)),
    "DATABASE_URL": f"postgresql://postgres:{pg}@postgres:5432/postgres",
    "CLICKHOUSE_PASSWORD": h(24),
    "MINIO_ROOT_PASSWORD": h(24),
    "REDIS_AUTH": h(24),
    "SALT": h(32),
    "ENCRYPTION_KEY": h(32),  # 64 hex characters, as Langfuse requires
    "NEXTAUTH_SECRET": h(32),
    "LANGFUSE_PUBLIC_KEY": "pk-lf-" + h(16),
    "LANGFUSE_SECRET_KEY": "sk-lf-" + h(16),
    "LANGFUSE_INIT_USER_EMAIL": "canary@example.com",  # fictional, a reserved example domain
    "LANGFUSE_INIT_USER_PASSWORD": h(16),
}
with open(sys.argv[1], "x", encoding="utf-8") as fh:  # "x": never overwrite credentials that match existing volumes
    fh.write("# Local Langfuse stack credentials, generated by make langfuse-up. Git-ignored; deleted by make langfuse-down.\n")
    for k, v in values.items():
        fh.write(f"{k}={v}\n")
EOF
  echo "generated local credentials in $ENV_FILE (git-ignored, mode 600; not printed)"
}

wait_healthy() {
  local port url deadline
  port=$(sed -n 's/^LANGFUSE_PORT=//p' "$ENV_FILE")
  url="http://localhost:${port:-3000}/api/public/health"
  deadline=$((SECONDS + ${LANGFUSE_UP_TIMEOUT:-300}))
  until curl -fs -o /dev/null "$url"; do
    if [ "$SECONDS" -ge "$deadline" ]; then
      echo "Langfuse did not answer on $url within ${LANGFUSE_UP_TIMEOUT:-300}s" >&2
      compose "$ENV_FILE" ps >&2
      exit 1
    fi
    sleep 3
  done
  echo "Langfuse is up: http://localhost:${port:-3000} (log in with the user in $ENV_FILE)"
}

case "${1:-}" in
  up)
    [ -f "$ENV_FILE" ] || generate_env
    compose "$ENV_FILE" up -d --quiet-pull
    wait_healthy
    ;;
  down)
    if [ -f "$ENV_FILE" ]; then
      compose "$ENV_FILE" down -v --remove-orphans
      rm -f "$ENV_FILE"
    else
      # No env file: compose still needs every variable to parse the file; placeholders are enough to remove things.
      tmp=$(mktemp)
      sed -n 's/.*\${\([A-Z_]*\):?.*/\1=x/p' "$COMPOSE_FILE" | sort -u >"$tmp"
      compose "$tmp" down -v --remove-orphans
      rm -f "$tmp"
    fi
    left=$(docker ps -a -q --filter "label=com.docker.compose.project=$PROJECT"; docker volume ls -q --filter "label=com.docker.compose.project=$PROJECT")
    if [ -n "$left" ]; then
      echo "left over from $PROJECT:" >&2
      echo "$left" >&2
      exit 1
    fi
    echo "stack $PROJECT is down: no container and no volume left"
    ;;
  check)
    [ -f "$ENV_FILE" ] || { echo "no $ENV_FILE: run make langfuse-up first" >&2; exit 2; }
    env -u ANTHROPIC_API_KEY "$PY" scripts/observability/langfuse_roundtrip.py --env-file "$ENV_FILE" "${@:2}"
    ;;
  *)
    echo "usage: $0 up|down|check" >&2
    exit 2
    ;;
esac
